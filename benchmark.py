"""Measure end-to-end inference throughput and write a runtime report.

    python benchmark.py --input data/test/lq

WHY this script exists:
    KLA scores end-to-end throughput and asks us to report runtime, batch
    size, hardware, software versions and the timing method. Rather than
    quoting a number from memory, this script measures it and writes
    results/runtime_report.md so the figures in our slides are traceable.

TIMING METHOD (the definition KLA gave):
    End-to-end runtime = disk reading + preprocessing + CPU-to-GPU transfer
    + model execution + GPU-to-CPU transfer + post-processing + saving.
    We time exactly that: the clock starts before the first file is read
    and stops after the last file is written. On GPU we call
    torch.cuda.synchronize() before stopping, because GPU work is
    asynchronous and would otherwise appear falsely fast.
"""

import argparse
import platform
import subprocess
import sys
import time
from pathlib import Path

import torch

from inference import load_model, restore_batch
from src.utils.image_io import list_images, load_image, save_image


def environment_report(device):
    """Collect the hardware/software facts KLA asks us to state."""
    lines = [
        f"- **CPU**: {platform.processor() or platform.machine()}",
        f"- **Device used**: {device.type.upper()}",
    ]
    if device.type == "cuda":
        lines.append(f"- **GPU**: {torch.cuda.get_device_name(0)} "
                     f"({torch.cuda.get_device_properties(0).total_memory / 1e9:.1f} GB)")
        lines.append(f"- **CUDA**: {torch.version.cuda}")
    lines += [
        f"- **OS**: {platform.system()} {platform.release()}",
        f"- **Python**: {sys.version.split()[0]}",
        f"- **PyTorch**: {torch.__version__}",
    ]
    return lines


def run_once(model, config, paths, device, batch_size, out_dir):
    """One full end-to-end pass. Returns (total, read, compute, save) seconds."""
    start_total = time.time()

    start_read = time.time()
    images = [load_image(p, config["channels"]) for p in paths]
    read_s = time.time() - start_read

    compute_s = save_s = 0.0
    for start in range(0, len(images), batch_size):
        chunk = images[start:start + batch_size]
        names = paths[start:start + batch_size]

        t0 = time.time()
        restored = restore_batch(model, torch.stack(chunk), device)
        if device.type == "cuda":
            torch.cuda.synchronize()   # GPU is async — wait before stopping the clock
        compute_s += time.time() - t0

        t0 = time.time()
        for path, image in zip(names, restored):
            save_image(image, out_dir / f"{path.stem}.npy")
        save_s += time.time() - t0

    return time.time() - start_total, read_s, compute_s, save_s


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", default="data/test/lq")
    parser.add_argument("--ckpt", default="weights/model.pth")
    parser.add_argument("--batch-sizes", type=int, nargs="+", default=[1, 4, 8, 16])
    parser.add_argument("--out", default="results/runtime_report.md")
    args = parser.parse_args()

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model, config = load_model(args.ckpt, device)
    paths = list_images(args.input)
    scratch = Path("outputs/_benchmark")
    scratch.mkdir(parents=True, exist_ok=True)

    sample = load_image(paths[0], config["channels"])
    in_size = f"{sample.shape[-2]}x{sample.shape[-1]}"
    out_size = f"{sample.shape[-2] * config['scale']}x{sample.shape[-1] * config['scale']}"

    # One untimed warm-up: the first call allocates buffers and, on GPU,
    # compiles kernels — timing it would blame the model for setup cost.
    restore_batch(model, sample.unsqueeze(0), device)

    print(f"benchmarking {len(paths)} images ({in_size} -> {out_size}) on {device.type}")
    rows = []
    for batch_size in args.batch_sizes:
        total, read_s, compute_s, save_s = run_once(
            model, config, paths, device, batch_size, scratch)
        per_image_ms = total / len(paths) * 1000
        rows.append((batch_size, total, read_s, compute_s, save_s, per_image_ms,
                     len(paths) / total))
        print(f"  batch {batch_size:3d}: {total:7.2f} s total, "
              f"{per_image_ms:7.1f} ms/image, {len(paths)/total:5.2f} img/s")

    best = min(rows, key=lambda r: r[1])

    report = [
        "# End-to-end runtime report",
        "",
        f"Generated by `benchmark.py` on {time.strftime('%Y-%m-%d')}.",
        "",
        "## Hardware and software",
        "",
        *environment_report(device),
        f"- **Model**: NAFNet-SR x{config['scale']}, width {config['width']}, "
        f"{config['n_blocks']} blocks "
        f"({sum(p.numel() for p in model.parameters())/1e6:.2f} M parameters)",
        f"- **Images**: {len(paths)} files, {in_size} -> {out_size}, float32 .npy",
        "",
        "## Timing method",
        "",
        "The clock starts before the first file is read and stops after the last",
        "file is written, covering disk read, preprocessing, host-to-device",
        "transfer, model execution, device-to-host transfer, clipping and saving.",
        "One untimed warm-up pass precedes measurement; on CUDA,",
        "`torch.cuda.synchronize()` is called before each stop because GPU work",
        "is asynchronous.",
        "",
        "## Results",
        "",
        "| Batch size | End-to-end | Read | Model+transfer | Save | Per image | Throughput |",
        "|---|---|---|---|---|---|---|",
    ]
    for b, total, r, c, s, ms, ips in rows:
        report.append(f"| {b} | {total:.2f} s | {r:.2f} s | {c:.2f} s | {s:.2f} s "
                      f"| {ms:.1f} ms | {ips:.2f} img/s |")
    report += [
        "",
        f"**Best configuration on this machine: batch size {best[0]}** — "
        f"{best[1]:.2f} s end-to-end for {len(paths)} images "
        f"({best[5]:.1f} ms per image, {best[6]:.2f} images/second).",
        "",
        "Note: batching helps most on a GPU, where it hides host-to-device",
        "transfer latency behind computation. On a CPU the work is already",
        "compute-bound, so larger batches give little or no gain.",
    ]

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(report), encoding="utf-8")
    print(f"\nreport written to {out_path}")


if __name__ == "__main__":
    main()
